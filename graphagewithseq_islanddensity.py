class HierarchicalNet(nn.Module):
    """
    方案二：Attention门控调制
    序列特征(常数，区分CpG位点) → 调制甲基化值的权重
    不做直接拼接，避免污染PNA
    """
    def __init__(self, deg, seq_len=122, original_dim=10, seq_embed_dim=8, num_cpgs=20000):
        super(HierarchicalNet, self).__init__()

        self.original_dim = original_dim

        # ===== 序列统计特征 → 甲基化重要性门控 =====
        # 序列特征决定"这个CpG位点的甲基化变化对年龄预测有多重要"
        self.importance_gate = nn.Sequential(
            nn.Linear(8, 16),
            nn.ReLU(),
            nn.Linear(16, 1),
            nn.Sigmoid()
        )

        # ===== 序列特征 → 2维位置附加信息 =====
        self.seq_proj = nn.Sequential(
            nn.Linear(8, 8),
            nn.ReLU(),
            nn.Linear(8, 2)
        )

        # PNA输入: 1(调制甲基化) + (original_dim-1)(原始位置特征) + 2(序列附加) = original_dim+2
        self.fused_dim = original_dim + 2  # = 12

        aggregators = ['mean', 'max', 'std', 'min']
        scalers = ['identity', 'amplification', 'attenuation']

        self.LastLayer = PNAConv(
            in_channels=self.fused_dim,
            out_channels=1,
            aggregators=aggregators,
            scalers=scalers,
            deg=deg,
            edge_dim=4,
            towers=1,
            pre_layers=1,
            post_layers=1,
            divide_input=False
        )

        self.mlp = nn.Sequential(
            nn.Linear(num_cpgs, 1024), nn.ReLU(),
            nn.Linear(1024, 656),      nn.SELU(),
            nn.Linear(656, 256),       nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(256, 124),       nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(124, 64),        nn.SELU(),
            nn.Linear(64, 32),         nn.ReLU(),
            nn.Linear(32, 8),          nn.ReLU(),
            nn.Linear(8, 1)
        )

    def forward(self, x_original, x_seq, edge_index, edge_attr, batch):
        """
        x_original: [num_nodes, original_dim]
                    第0列 = 甲基化值（样本间变化）
                    第1-9列 = 位置特征（CpG间变化，样本间不变）
        x_seq:      [num_nodes, 8]  序列统计特征（样本间不变，CpG间变化）
        """
        # 1. 序列特征生成门控权重，对甲基化值加权
        #    生物学含义：序列context决定该位点甲基化变化的预测重要性
        importance = self.importance_gate(x_seq)           # [num_nodes, 1]
        meth_modulated = x_original[:, 0:1] * importance  # [num_nodes, 1]

        # 2. 序列特征额外贡献2维附加信息（位置信息补充）
        seq_extra = self.seq_proj(x_seq)                   # [num_nodes, 2]

        # 3. 拼接：调制甲基化 + 原始位置特征(完全不动) + 序列附加
        x = torch.cat([
            meth_modulated,     # [num_nodes, 1]  含样本变化信息
            x_original[:, 1:], # [num_nodes, 9]  原始位置特征，梯度畅通
            seq_extra           # [num_nodes, 2]  序列位置补充
        ], dim=-1)              # → [num_nodes, 12]

        x = self.LastLayer(x, edge_index, edge_attr)
        x = F.relu(x)
        out = self.mlp(x.T)
        return out.flatten()


