def data_loader_maker_hierarchical(X_, y_, edge_index, edge_attr,
                                    filtered_information, seq_data,
                                    user_selected_features, batch_size=1):
    """
    创建包含序列数据的DataLoader（修改版）

    与原始data_loader_maker的区别：
    - 新增参数 seq_data：预处理好的序列数据
    - Data对象新增 x_seq 字段

    参数：
    - X_: 甲基化数据 DataFrame [num_samples, num_cpgs]
    - y_: 年龄标签 Series [num_samples]
    - edge_index: 边索引 [2, num_edges]
    - edge_attr: 边属性 [num_edges, 3]
    - filtered_information: 筛选后的CpG信息 DataFrame
    - seq_data: 预处理好的序列数据 [num_cpgs, seq_len, 4]（新增）
    - user_selected_features: 选择的特征列名列表
    - batch_size: 批次大小

    返回：
    - DataLoader
    """
    current_graph = []

    # 将序列数据转换为tensor（所有样本共享同一套序列）
    seq_tensor = torch.tensor(seq_data, dtype=torch.float32)

    for row in range(len(X_)):
        # 原始特征处理（与原版相同）
        x = pd.concat([X_.iloc[row, :], filtered_information[user_selected_features]], axis=1, join='inner')
        x_original = torch.tensor(x.to_numpy().astype('float'), dtype=torch.float32)

        # 年龄标签
        y = torch.tensor(y_.iloc[row], dtype=torch.float32)

        # 创建图数据对象（新增x_seq字段）
        graph = Data(
            x=x_original,       # 原始节点特征 [num_cpgs, original_dim]
            x_seq=seq_tensor,   # 序列数据 [num_cpgs, seq_len, 4]（新增）
            y=y,
            edge_index=edge_index,
            edge_attr=edge_attr
        )
        current_graph.append(graph)

    return DataLoader(current_graph, batch_size=batch_size)


