def load_cv_checkpoint(path):
    """
    尝试加载检查点。
    返回：(ckpt_dict | None)
      - 若文件不存在，返回 None
      - 若存在，返回完整 ckpt 字典，由调用方决定如何使用

    调用方拿到 ckpt 后：
      1. 先用 ckpt['deg'] 创建模型
      2. 再调用 model.load_state_dict(ckpt['model_state_dict'])
    这样保证模型结构与保存时完全一致。
    """
    if not os.path.exists(path):
        print(f"  📂 未发现检查点，从头开始训练...")
        return None

    print(f"  📂 发现检查点: {path}")
    ckpt = torch.load(path, map_location=device)
    print(f"  ✅ 检查点读取成功")
    print(f"     保存时 Epoch:    {ckpt['epoch']}")
    print(f"     当前最佳 Val MAE:  {ckpt.get('best_val_mae', float('inf')):.4f}")
    print(f"     当前最佳 Test MAE: {ckpt.get('best_test_mae', float('inf')):.4f}")
    print(f"     已完成 {len(ckpt.get('train_losses', []))} 个 epoch")

    # 检查 deg 是否存在（兼容旧版本checkpoint）
    if 'deg' not in ckpt:
        print(f"  ⚠️  旧版检查点不含 deg，将重新计算 deg（正常现象，仅首次续训时出现）")

    return ckpt


