# make_graph函数
# 方案：不新增边，只给现有边打同CpG岛标记（第4维）
# 同CpG岛 = 两个位点在同一个CpG岛内，受同一启动子调控
# 保证所有边都有共甲基化信号支撑，PNA层不会崩溃
def make_graph(information, threshold_corr, threshold_dist, meth, cpg2node, chromosomes):
    src = []
    dst = []
    weights = []

    chromosomes = information.Chr.values
    genes = information.Symbol.values

    # 同染色体邻接矩阵
    print('makeing same chromo adjacency...')
    chromosomes = np.array(chromosomes)
    chromosome_adj = (chromosomes[:, None] == chromosomes).astype(np.float32)

    # 距离矩阵
    print('making distance matrix .......')
    base_pair = information.MapInfo.values
    pairwise_distances = pdist(base_pair.reshape(-1, 1))
    distance_matrix = squareform(pairwise_distances)

    # 同基因邻接矩阵
    print('makeing same gene adjacency...')
    genes = np.array(genes)
    genes_adj = (genes[:, None] == genes).astype(np.float32)

    # 共甲基化相关性矩阵
    print('makeing comethylation adjacency...')
    adj = np.corrcoef(meth.to_numpy(), rowvar=False)

    # ── 新增：同CpG岛邻接矩阵（给现有边打标记，不新增边）──
    # 两个位点在同一个CpG岛内 → 第4维 = 1.0，否则 = 0.0
    # 生物学意义：同CpG岛的位点受同一启动子调控，
    #             在衰老过程中倾向于协同甲基化变化
    print('making same CpG island label matrix...')
    n = len(information)
    same_island_adj = np.zeros((n, n), dtype=np.float32)
    try:
        # 从information里提取CpG岛位置信息
        island_locations = information['CPG_ISLAND_LOCATIONS'].values

        # 建立CpG岛位置 → 位点索引列表的映射
        island_to_indices = {}
        for idx, loc in enumerate(island_locations):
            if pd.notna(loc) and str(loc).strip() != '':
                loc_str = str(loc).strip()
                if loc_str not in island_to_indices:
                    island_to_indices[loc_str] = []
                island_to_indices[loc_str].append(idx)

        # 同一CpG岛内的所有位点对互相标记
        island_pairs = 0
        for loc, indices in island_to_indices.items():
            if len(indices) >= 2:
                for i in range(len(indices)):
                    for j in range(i + 1, len(indices)):
                        ii, jj = indices[i], indices[j]
                        same_island_adj[ii, jj] = 1.0
                        same_island_adj[jj, ii] = 1.0
                        island_pairs += 1

        nonzero = int(np.count_nonzero(same_island_adj))
        multi_island_count = sum(1 for v in island_to_indices.values() if len(v) >= 2)
        print(f'  共处理 {len(island_to_indices)} 个CpG岛')
        print(f'  有多个位点的CpG岛: {multi_island_count} 个')
        print(f'  同CpG岛位点对: {island_pairs:,} 对（单向）')
        print(f'  same_island矩阵非零元素: {nonzero:,}（双向）')
    except Exception as e:
        print(f'  ⚠️  同CpG岛矩阵构建失败（{e}），第4维全为0')

    # ── 边过滤：条件与原作者完全相同，不新增任何边 ──
    # 所有边都保证有共甲基化相关性支撑，PNA层可以正常工作
    src, dst = np.where(
        (
            ((chromosome_adj == 1) &
                ((np.abs(adj) > SECONDARY_THRESHOLD) |
                 ((abs(distance_matrix) < threshold_dist) & (np.abs(adj) > TERTIARY_THRESHOLD))
                )
            )
            | (np.abs(adj) > threshold_corr)
        )
        & (np.arange(adj.shape[0])[:, None] != np.arange(adj.shape[1]))
    )

    print('making edge weights.....')

    # ── 边权重：4维 ──
    # 维度1：共甲基化相关性（PNA学习的核心信号，所有边均有值）
    # 维度2：同染色体（0或1）
    # 维度3：同基因（0或1）
    # 维度4：同CpG岛标记（1.0=同岛，0.0=不同岛）
    weights = np.column_stack([
        adj[src, dst],               # 维度1：共甲基化相关性
        chromosome_adj[src, dst],    # 维度2：同染色体
        genes_adj[src, dst],         # 维度3：同基因
        same_island_adj[src, dst]    # 维度4：同CpG岛标记（新增）
    ])

    # 统计有同CpG岛标记的边数量
    island_labeled_edges = int(np.count_nonzero(same_island_adj[src, dst]))
    total_edges = len(src)
    print(f'  总边数: {total_edges:,}')
    print(f'  有同CpG岛标记的边: {island_labeled_edges:,} ({island_labeled_edges/total_edges*100:.2f}%)')

    edge_index = [torch.tensor(src, dtype=torch.int64), torch.tensor(dst, dtype=torch.int64)]
    edge_weight = weights
    edge_index = torch.stack(edge_index, dim=0)
    edge_attr = torch.tensor(edge_weight, dtype=torch.float32).reshape(-1, EDGE_DIM)
    print("shape of edge:", edge_index.shape)
    return edge_index, edge_attr


# compute_max_in_degree_and_histogram函数（与原始代码第523-561行一致）
def compute_max_in_degree_and_histogram(train_data_loader):
    """
    Compute the maximum in-degree and in-degree histogram tensor.
    """
    device_cpu = torch.device("cpu")

    max_degree = -1
    num_of_nodes = 0

    for idx, data in enumerate(train_data_loader):
        edge_index = data.edge_index[1].to(device_cpu)
        max_degree = max(max_degree, int(edge_index.max()))
        num_of_nodes += data.num_nodes
        if (idx + 1) % 100 == 0:
            print(f"Processed {idx + 1} batches, {num_of_nodes} nodes so far...")
        break

    deg = torch.zeros(max_degree + 1, dtype=torch.long, device=device_cpu)
    for idx, data in enumerate(train_data_loader.dataset):
        edge_index = data.edge_index[1].to(device_cpu)
        d = torch.bincount(edge_index, minlength=max_degree + 1).to(device_cpu)
        deg += d
        if (idx + 1) % 100 == 0:
            print(f"Processed {idx + 1} samples...")

    return max_degree, deg


