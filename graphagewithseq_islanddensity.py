class DNASequenceEncoder(nn.Module):
    """
    DNA序列编码器 - 1D CNN

    架构：
    输入: [batch, seq_len, 4] (One-Hot编码)
    输出: [batch, embed_dim] (序列嵌入向量)

    使用多尺度卷积核捕获不同长度的序列模式：
    - kernel=3: 捕获3-mer模式（如CpG二核苷酸）
    - kernel=5: 捕获5-mer模式
    - kernel=7: 捕获更长的motif（如转录因子结合位点）
    """

    def __init__(self, seq_len=122, embed_dim=64):
        """
        参数：
        - seq_len: 输入序列长度
        - embed_dim: 输出嵌入维度
        """
        super(DNASequenceEncoder, self).__init__()

        self.seq_len = seq_len
        self.embed_dim = embed_dim

        # 第一层卷积：kernel_size=3
        self.conv1 = nn.Sequential(
            nn.Conv1d(in_channels=4, out_channels=32, kernel_size=3, padding=1),
            nn.BatchNorm1d(32),
            nn.ReLU()
        )

        # 第二层卷积：kernel_size=5
        self.conv2 = nn.Sequential(
            nn.Conv1d(in_channels=32, out_channels=64, kernel_size=5, padding=2),
            nn.BatchNorm1d(64),
            nn.ReLU()
        )

        # 第三层卷积：kernel_size=7
        self.conv3 = nn.Sequential(
            nn.Conv1d(in_channels=64, out_channels=128, kernel_size=7, padding=3),
            nn.BatchNorm1d(128),
            nn.ReLU()
        )

        # 全局最大池化
        self.global_max_pool = nn.AdaptiveMaxPool1d(1)

        # 全连接层：投影到嵌入维度
        self.fc = nn.Sequential(
            nn.Linear(128, embed_dim),
            nn.ReLU(),
            nn.Dropout(0.1)
        )

    def forward(self, x):
        """
        前向传播

        参数：
        - x: [batch, seq_len, 4]

        返回：
        - embeddings: [batch, embed_dim]
        """
        # 转置：[batch, seq_len, 4] -> [batch, 4, seq_len]
        x = x.permute(0, 2, 1)

        # 卷积层
        x = self.conv1(x)  # [batch, 32, seq_len]
        x = self.conv2(x)  # [batch, 64, seq_len]
        x = self.conv3(x)  # [batch, 128, seq_len]

        # 全局最大池化
        x = self.global_max_pool(x)  # [batch, 128, 1]
        x = x.squeeze(-1)  # [batch, 128]

        # 全连接层
        embeddings = self.fc(x)  # [batch, embed_dim]

        return embeddings


